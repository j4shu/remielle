/// Reverse lookup: suit id → friendly `Set` name, or null if unknown.
pub fn setName(id: u32) ?[]const u8 {
    inline for (@typeInfo(Set).@"enum".fields) |f|
        if (f.value == id) return f.name;
    return null;
}

/// Reverse lookup: weapon id → friendly `Weapon` name, or null if unknown.
pub fn weaponName(id: u32) ?[]const u8 {
    inline for (@typeInfo(Weapon).@"enum".fields) |f|
        if (f.value == id) return f.name;
    return null;
}

/// Reverse lookup: avatar id → friendly `Avatar` name, or null if unknown.
pub fn avatarName(id: u32) ?[]const u8 {
    inline for (@typeInfo(Avatar).@"enum".fields) |f|
        if (f.value == id) return f.name;
    return null;
}

/// Friendly name for a property key (display only).
pub fn propName(key: u32) []const u8 {
    return switch (key) {
        11103 => "HpFlat",
        11102 => "HpPct",
        12103 => "AtkFlat",
        12102 => "AtkPct",
        12202 => "Impact",
        13103 => "DefFlat",
        13102 => "DefPct",
        20103 => "CritRate",
        21103 => "CritDmg",
        23203 => "PenFlat",
        23103 => "PenRatio",
        30502 => "EnergyRegen",
        31203 => "AnomProf",
        31402 => "AnomMastery",
        31503 => "PhysDmg",
        31603 => "FireDmg",
        31703 => "IceDmg",
        31803 => "ElecDmg",
        31903 => "EtherDmg",
        32303 => "WindDmg",
        else => "?",
    };
}
