//! Friendly ZZZ name tables shared by tools/builds/edit-save.zig and tools/builds/inspect-save.zig:
//! the `Set` enum (set name → suit id), the `Avatar` enum (character name → avatar id),
//! the `Weapon` enum (W-Engine name → weapon id), and `propName` (property key →
//! readable name). Kept in one place so the writer (edit-save) and the reader
//! (inspect-save) can never disagree about a name.

const std = @import("std");

/// Gear-uid encoding bases. In the save, a gear item stores its raw uid `n`, but an
/// avatar's reference to it stores `n + base` (battle.zig subtracts the base to resolve
/// the reference back to the item). The two inventories use DIFFERENT bases, so both the
/// writer (edit-save) and the reader (inspect-save) import them from here to stay in lockstep:
/// - discs: an avatar slot stores `uid + equipment_uid_base` (Equipment.Uid.base in
///   gamesv/src/logic/Properties/Equipment.zig); the slot list is positional, 6 entries.
/// - W-Engines: an avatar's `weapon_uid` stores `uid + weapon_uid_base` (Weapon.Uid.base in
///   gamesv/src/logic/Properties/Weapon.zig); a single scalar, `0` = no weapon.
/// Get a base wrong and auto-equip silently references nothing.
pub const equipment_uid_base: u32 = 0x2_0000;
pub const weapon_uid_base: u32 = 0x1_0000;

